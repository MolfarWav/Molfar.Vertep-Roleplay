/**
 * Copies the skill's recipe files into src/lib/forge-recipes.ts, so the editor can start a new agent from one.
 *
 *   bun scripts/sync-agent-recipes.ts          rewrite src/lib/forge-recipes.ts
 *   bun scripts/sync-agent-recipes.ts --check  exit 1 when it is out of date (the tests do the same)
 *
 * The recipes live once, as JSON in .skills/agent-craft/references (Molfar reads them there); the app cannot import
 * from that folder, so a generated module carries them. Edit the JSON, run this, commit both.
 */
import fs from 'node:fs'

const root = new URL('../', import.meta.url)
const dir = new URL('.skills/agent-craft/references/', root)
const out = new URL('src/lib/forge-recipes.ts', root)

export function generated(): string {
  const names = fs.readdirSync(dir).filter((f) => f.endsWith('.vertep-agent.json')).sort()
  const items = names.map((f) => `  ${JSON.stringify(JSON.parse(fs.readFileSync(new URL(f, dir), 'utf8')))},`)
  return [
    '// GENERATED by bun scripts/sync-agent-recipes.ts from .skills/agent-craft/references/*.vertep-agent.json. Do not edit.',
    "import type { CanvasFile } from '@/canvas-kit/graph'",
    '',
    '/** Working agents the editor offers as a start. */',
    'export const AGENT_RECIPES: CanvasFile[] = [',
    ...items,
    ']',
    '',
  ].join('\n')
}

if (import.meta.main) {
  const next = generated()
  const now = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : ''
  if (process.argv.includes('--check')) {
    if (next !== now) { console.error('src/lib/forge-recipes.ts is out of date: run bun scripts/sync-agent-recipes.ts'); process.exit(1) }
  } else if (next !== now) fs.writeFileSync(out, next)
}
